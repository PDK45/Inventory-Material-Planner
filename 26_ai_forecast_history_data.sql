-- LEARNING: Why do we generate synthetic data?
-- The Holt-Winters model needs MINIMUM 2 full seasonal cycles
-- (24 months for monthly data) to learn a reliable seasonal pattern.
-- Our sample data has only a few manual forecasts, so we seed 24
-- months of realistic demand with built-in seasonality and trend.
--
-- The seasonal pattern is based on Indian manufacturing calendar:
--   Jan:0.85  Feb:0.80  Mar:1.10(FY-end)  Apr:0.90  May:0.88
--   Jun:0.92  Jul:0.95  Aug:1.00  Sep:1.05  Oct:1.25(Diwali)
--   Nov:1.15  Dec:1.15(Year-end budget spend)
-- Sum = 12.00  -->  Average = 1.00  ✓ (correct for multiplicative)
--
-- Year-over-year growth = ~8% (2025 vs 2024), realistic for
-- India's industrial manufacturing sector.
-- ============================================================

